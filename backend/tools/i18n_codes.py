"""Developer tool: copies the code labels (statuses, types) from the UI catalogues into app/locales/codes.py,
so PDF reports show the same wording as the screens.

    python tools/i18n_codes.py          # rewrite app/locales/codes.py
    python tools/i18n_codes.py --check  # exit 1 if it is out of date
"""
from __future__ import annotations

import json
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "backend" / "app" / "locales" / "codes.py"


def build() -> str:
    codes = {}
    for lang in ("en", "fr"):
        d = json.loads((ROOT / "frontend" / "src" / "i18n" / f"{lang}.json").read_text(encoding="utf-8"))
        codes[lang] = {**d.get("codes", {}), **d.get("status", {})}
    return ('"""Labels of codes (statuses, types) — generated by tools/i18n_codes.py from the UI catalogues. Do not edit."""\n\n'
            f"CODES: dict[str, dict[str, str]] = {pprint.pformat(codes, width=140, sort_dicts=True)}\n")


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
